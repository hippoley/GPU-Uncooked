import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
const base="http://127.0.0.1:8765/playground/chapters/";
mkdirSync("browser-artifacts",{recursive:true});
const browser=await chromium.launch({headless:true});
const failures=[];
for(const device of [{name:"desktop",width:1440,height:900},{name:"mobile",width:390,height:844}]){
 const page=await browser.newPage({viewport:device,deviceScaleFactor:1});
 page.on("pageerror",error=>failures.push(device.name+": "+error.message));
 const visit=async(chapter,path)=>{
   const response=await page.goto(base+path,{waitUntil:"networkidle"});
   assert.equal(response.status(),200,chapter+" HTTP status");
   await page.screenshot({path:"browser-artifacts/"+device.name+"-"+chapter+".png",fullPage:true});
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+3);
   assert.equal(overflow,false,chapter+" horizontal overflow on "+device.name);
 };
 await visit("hub","index.html");
 assert.equal(await page.locator("a[href='./01-thread-mapping/index.html']").count(),1);
 await page.locator("a[href='./01-thread-mapping/index.html']").click();
 await page.locator("#elements").evaluate(el=>{el.value="50";el.dispatchEvent(new Event("input",{bubbles:true}));});
 await page.locator("#block-size").evaluate(el=>{el.value="16";el.dispatchEvent(new Event("input",{bubbles:true}));});
 await page.locator("#prediction").fill("4");
 await page.locator("#check").click();
 assert.match(await page.locator("#feedback").innerText(),/Correct/);
 await page.locator(".thread").first().click();
 assert.match(await page.locator("#thread-info").innerText(),/blockIdx.x/);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-chapter01.png",fullPage:true});
 await page.locator('a[href="../02-warp-divergence/index.html"]').click();
 await page.locator('[data-preset="half"]').click();
 assert.equal(await page.locator("#paths").innerText(),"2");
 await page.locator(".lane").first().click();
 assert.equal(await page.locator("#count-a").innerText(),"15 lanes");
 await page.screenshot({path:"browser-artifacts/"+device.name+"-chapter02.png",fullPage:true});
 await page.locator('a[href="../03-memory-coalescing/index.html"]').click();
 assert.equal(await page.locator("#memory-explorer").isHidden(),true);
 await page.locator("#guess").fill("4");
 await page.locator("#check").click();
 assert.match(await page.locator("#feedback").innerText(),/Correct/);
 assert.equal(await page.locator("#memory-explorer").isVisible(),true);
 await page.locator('[data-preset="stride8"]').click();
 assert.equal(await page.locator("#memory-explorer").isHidden(),true);
 await page.locator("#guess").fill("32");
 await page.locator("#check").click();
 assert.equal(await page.locator("#sectors").innerText(),"32");
 await page.screenshot({path:"browser-artifacts/"+device.name+"-chapter03.png",fullPage:true});
 await page.close();
}
await browser.close();
writeFileSync("browser-artifacts/report.json",JSON.stringify({status:failures.length?"failed":"passed",failures,devices:["desktop","mobile"],chapters:3},null,2));
assert.deepEqual(failures,[]);
console.log("PASS: three chapters, challenge, explorer, navigation, screenshots in desktop and mobile");
