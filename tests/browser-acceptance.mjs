import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
const base="http://127.0.0.1:8765/playground/chapters/";
mkdirSync("browser-artifacts",{recursive:true});
const browser=await chromium.launch({headless:true});
const failures=[];
for(const device of [{name:"desktop",width:1440,height:900},{name:"mobile",width:390,height:844}]){
 const page=await browser.newPage({viewport:{width:device.width,height:device.height},deviceScaleFactor:1});
 page.on("pageerror",error=>failures.push(device.name+": "+error.message));
 const visit=async(chapter,path)=>{
   const response=await page.goto(base+path,{waitUntil:"networkidle"});
   assert.equal(response.status(),200,chapter+" HTTP status");
   await page.screenshot({path:"browser-artifacts/"+device.name+"-"+chapter+".png",fullPage:true});
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+3);
   assert.equal(overflow,false,chapter+" horizontal overflow on "+device.name);
 };
 await visit("hub","index.html");
 assert.equal(await page.locator(".cards a[href='./01-thread-mapping/index.html']").count(),1);
 await page.locator(".cards a[href='./01-thread-mapping/index.html']").click();
 await page.locator("#elements").evaluate(el=>{el.value="50";el.dispatchEvent(new Event("input",{bubbles:true}));});
 await page.locator("#block-size").evaluate(el=>{el.value="16";el.dispatchEvent(new Event("input",{bubbles:true}));});
 await page.locator("#prediction").fill("4");
 await page.locator("#check").click();
 assert.match(await page.locator("#feedback").innerText(),/Correct/);
 await page.locator(".thread").first().click();
 assert.match(await page.locator("#thread-info").innerText(),/blockIdx.x/);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-chapter01.png",fullPage:true});
 await page.locator('a[href="../02-warp-divergence/index.html"]').click();
 await page.locator('[data-preset="half"]').click();
 assert.equal(await page.locator("#paths").innerText(),"2");
 await page.locator(".lane").first().click();
 assert.equal(await page.locator("#count-a").innerText(),"15 lanes");
 await page.screenshot({path:"browser-artifacts/"+device.name+"-chapter02.png",fullPage:true});
 await page.locator('a[href="../03-memory-coalescing/index.html"]').click();
 assert.equal(await page.locator("#memory-explorer").isHidden(),true);
 await page.locator("#guess").fill("4");
 await page.locator("#check").click();
 assert.match(await page.locator("#feedback").innerText(),/Correct/);
 assert.equal(await page.locator("#memory-explorer").isVisible(),true);
 await page.locator('[data-preset="stride8"]').click();
 assert.equal(await page.locator("#memory-explorer").isHidden(),true);
 await page.locator("#guess").fill("32");
 await page.locator("#check").click();
 assert.equal(await page.locator("#sectors").innerText(),"32");
 await page.screenshot({path:"browser-artifacts/"+device.name+"-chapter03.png",fullPage:true});
 await page.goto("http://127.0.0.1:8765/playground/arcade/index.html",{waitUntil:"networkidle"});
 assert.equal(await page.locator("#title").innerText(),"潜入显存海沟");
 await page.locator("#go").click();
 assert.equal(await page.locator("#modal").isHidden(),true);
 assert.equal(await page.locator("#mission-title").innerText(),"第一潜：探索失落的 L2 遗迹");
 const before=await page.locator("#o").innerText();
 await page.keyboard.down("ArrowDown");
 await page.waitForTimeout(1700);
 await page.keyboard.up("ArrowDown");
 await page.waitForTimeout(200);
 assert.ok(Number(await page.locator("#o").innerText())<Number(before),"Arcade oxygen depletes during active dive");
 await page.locator("#pulse-button").click();
 assert.notEqual(await page.locator("#pulse-status").innerText(),"READY","Pulse enters cooldown");
 assert.equal(await page.locator("#mission-card").isVisible(),true);
 assert.equal(await page.locator("#mission-kicker").isVisible(),true);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-arcade.png",fullPage:true});
 await page.goto("http://127.0.0.1:8765/playground/city/index.html",{waitUntil:"networkidle"});
 assert.match(await page.locator("#modal-title").innerText(),/今晚，城市属于你/);
 await page.locator("#start").click();
 assert.equal(await page.locator("#modal").isHidden(),true);
 // Starting at (469,394), approach the Thread Factory mission point (185,353).
 await page.keyboard.down("ArrowLeft");
 await page.waitForTimeout(1320);
 await page.keyboard.up("ArrowLeft");
 await page.keyboard.down("ArrowUp");
 await page.waitForTimeout(220);
 await page.keyboard.up("ArrowUp");
 await page.locator("#interact").click();
 assert.equal(await page.locator("#modal").isVisible(),true);
 assert.equal(await page.locator("#modal-title").innerText(),"线程工厂");
 assert.equal(await page.locator('#modal-actions a[href="../chapters/01-thread-mapping/index.html"]').count(),1);
 await page.locator("#modal-actions button").click();
 assert.equal(await page.locator("#modal").isHidden(),true);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-silicon-city.png",fullPage:true});
 // Separate 3D acceptance: rendered WebGL must initialize, not just return HTTP 200.
 await page.goto("http://127.0.0.1:8765/playground/city3d/index.html",{waitUntil:"domcontentloaded"});
 await page.waitForFunction(()=>document.documentElement.dataset.city3dReady==="true"||document.documentElement.dataset.city3dReady==="false",{timeout:20000});
 assert.equal(await page.locator("html").getAttribute("data-city3d-ready"),"true","True WebGL 3D scene must initialize");
 assert.equal(await page.locator("#loading").isHidden(),true);
 const sceneStats=await page.evaluate(()=>window.__CITY3D_DIAGNOSTICS);
 assert.ok(sceneStats?.webgl,"Real WebGL scene must be rendered");
 assert.ok(sceneStats.drawCalls>0&&sceneStats.triangles>0,"A non-empty 3D scene must be rasterized");
 assert.ok(sceneStats.textures>=6,"Procedural road, facade and neon map textures must exist");
 await page.locator("#start").click();
 assert.equal(await page.locator("#intro").isHidden(),true);
 await page.keyboard.down("ArrowLeft");
 await page.waitForTimeout(250);
 await page.keyboard.up("ArrowLeft");
 await page.screenshot({path:"browser-artifacts/"+device.name+"-city3d.png",fullPage:true});
 await page.locator("#viewmode").click();
 assert.match(await page.locator("#viewmode").innerText(),/第一人称/);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-city3d-first-person.png",fullPage:true});
 await page.locator("#viewmode").click();
 assert.match(await page.locator("#viewmode").innerText(),/第三人称/);
 // Action -> model -> result -> next action: an actual playable freight mission.
 await page.goto("http://127.0.0.1:8765/playground/freight/index.html",{waitUntil:"networkidle"});
 assert.equal(await page.locator("#job").innerText(),"01 / 03");
 assert.equal(await page.locator("#sectors").innerText(),"64");
 await page.locator(".pallet").first().click();
 await page.locator("#consolidate").click();
 assert.equal(await page.locator("#sectors").innerText(),"58","Physical cargo consolidation must immediately reduce sector footprint");
 await page.locator("#reset").click();
 assert.equal(await page.locator("#sectors").innerText(),"64");
 await page.locator("#dispatch").click();
 await page.waitForTimeout(750);
 assert.match(await page.locator("#result").innerText(),/运输预算告急/);
 await page.locator("#regroup").click();
 assert.equal(await page.locator("#sectors").innerText(),"16");
 await page.locator("#dispatch").click();
 await page.locator("#result button").waitFor({state:"visible",timeout:5000});
 await page.locator("#result button").click();
 assert.equal(await page.locator("#job").innerText(),"02 / 03");
 for(let round=2;round<=3;round++){
  await page.locator("#regroup").click();
  assert.equal(await page.locator("#sectors").innerText(),"16");
  await page.locator("#dispatch").click();
  await page.locator("#result button").waitFor({state:"visible",timeout:5000});
  await page.locator("#result button").click();
 }
 const receipt=await page.evaluate(()=>JSON.parse(localStorage.getItem("gpu-uncooked.freight.v1")));
 assert.equal(receipt.completed,true);
 assert.ok(receipt.credits>0);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-freight-finished.png",fullPage:true});
 await page.goto("http://127.0.0.1:8765/playground/city3d/index.html",{waitUntil:"domcontentloaded"});
 await page.waitForFunction(()=>document.documentElement.dataset.city3dReady==="true"||document.documentElement.dataset.city3dReady==="false");
 assert.equal(await page.locator("html").getAttribute("data-city3d-ready"),"true");
 assert.equal(await page.locator("html").getAttribute("data-freight-cleared"),"true","Completed action must be visibly reflected back in city world");
 assert.match(await page.locator("#discovered").innerText(),/FREIGHT CLEARED/);
 await page.locator("#start").click();
 assert.equal(await page.locator("#intro").isHidden(),true);
 await page.screenshot({path:"browser-artifacts/"+device.name+"-freight-city-return.png",fullPage:true});
 await page.close();
}
await browser.close();
writeFileSync("browser-artifacts/report.json",JSON.stringify({status:failures.length?"failed":"passed",failures,devices:["desktop","mobile"],chapters:3,arcade:true,city:true},null,2));
assert.deepEqual(failures,[]);
console.log("PASS: three chapters, challenge, explorer, navigation, screenshots in desktop and mobile");
